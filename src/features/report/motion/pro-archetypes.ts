export function getProArchetypesForAction(actionType: string): ProArchetype[] {
  const normalized = actionType.toLowerCase().replace(/-/g, "_");
  let ids: ProArchetypeId[];

  if (normalized.includes("forehand") && !normalized.includes("volley")) {
    ids = ["alcaraz_forehand", "federer_forehand"];
  } else if (normalized.includes("one_handed") || normalized.includes("one_hand") || normalized.includes("slice")) {
    ids = ["federer_classic", "alcaraz_modern"];
  } else if (normalized.includes("backhand")) {
    ids = ["alcaraz_modern", "djokovic_compact"];
  } else if (normalized.includes("serve")) {
    ids = ["sampras_serve", "kick_serve"];
  } else if (normalized.includes("volley")) {
    ids = ["edberg_volley", "djokovic_compact"];
  } else {
    ids = ["alcaraz_modern", "djokovic_compact"];
  }

  return ids.map((id) => PRO_ARCHETYPES[id]).filter(Boolean);
}
